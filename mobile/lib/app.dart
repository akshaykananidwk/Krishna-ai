import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';

import 'core/router/app_router.dart';
import 'core/theme/app_theme.dart';
import 'features/auth/presentation/providers/auth_controller.dart';

/// Root widget. Triggers session restore once, then delegates all navigation
/// to the auth-aware [routerProvider].
class KrishnaApp extends ConsumerStatefulWidget {
  const KrishnaApp({super.key});

  @override
  ConsumerState<KrishnaApp> createState() => _KrishnaAppState();
}

class _KrishnaAppState extends ConsumerState<KrishnaApp> {
  @override
  void initState() {
    super.initState();
    WidgetsBinding.instance.addPostFrameCallback((_) {
      ref.read(authControllerProvider.notifier).bootstrap();
    });
  }

  @override
  Widget build(BuildContext context) {
    final router = ref.watch(routerProvider);
    return MaterialApp.router(
      title: 'Krishna AI',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light(),
      darkTheme: AppTheme.dark(),
      themeMode: ThemeMode.system,
      routerConfig: router,
    );
  }
}
